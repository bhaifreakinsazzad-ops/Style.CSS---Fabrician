-- FABRICIAN isolated Supabase commerce schema (PostgreSQL 15+).
-- Apply ONLY to the dedicated Fabrician project after approval; not PowerPointBD.
-- Every public table has RLS, with deny-by-default and no direct order writes.
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.fabrician_products (
  id text primary key,
  brand text not null,
  name_en text not null,
  name_bn text not null default '',
  category text not null,
  description_en text not null default '',
  image_url text not null default '',
  status text not null default 'draft' check (status in ('draft','active','hidden')),
  rights_cleared boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fabrician_variants (
  sku text primary key,
  product_id text not null references public.fabrician_products(id),
  color text not null,
  size text not null,
  price_bdt integer not null check(price_bdt >= 1 and price_bdt <= 10000000),
  stock_count integer not null default 0 check (stock_count >= 0),
  enabled boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists fabrician_variants_product_idx on public.fabrician_variants(product_id);

create table if not exists public.fabrician_settings (
  id text primary key check (id='main'),
  free_shipping_threshold_bdt integer not null default 5000 check(free_shipping_threshold_bdt >= 0),
  dhaka_shipping_bdt integer not null default 80 check(dhaka_shipping_bdt >= 0),
  outside_dhaka_shipping_bdt integer not null default 130 check(outside_dhaka_shipping_bdt >= 0),
  bundle_2_discount_bdt integer not null default 150 check(bundle_2_discount_bdt >= 0),
  bundle_3_discount_bdt integer not null default 300 check(bundle_3_discount_bdt >= 0)
);
insert into public.fabrician_settings (id) values ('main') on conflict(id) do nothing;

create table if not exists public.fabrician_orders (
  id uuid primary key default gen_random_uuid(),
  public_id text not null unique,
  request_key text not null unique,
  lookup_token_hash text not null,
  customer_name text not null,
  customer_phone text not null,
  delivery_address text not null,
  division text not null,
  payment_method text not null default 'cod' check(payment_method in ('cod')),
  payment_status text not null default 'unpaid' check(payment_status in ('unpaid','pending','paid','refunded')),
  fulfillment_status text not null default 'pending' check(fulfillment_status in ('pending','confirmed','packed','shipped','delivered','cancelled','returned')),
  courier_consignment_id text,
  subtotal_bdt integer not null check(subtotal_bdt >= 0),
  discount_bdt integer not null check(discount_bdt >= 0),
  delivery_fee_bdt integer not null check(delivery_fee_bdt >= 0),
  total_bdt integer not null check(total_bdt >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists fabrician_orders_phone_date_idx on public.fabrician_orders (customer_phone, created_at desc);

create table if not exists public.fabrician_order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.fabrician_orders(id) on delete cascade,
  sku text not null references public.fabrician_variants(sku),
  product_name text not null,
  color text not null,
  size text not null,
  quantity integer not null check (quantity between 1 and 20),
  unit_price_bdt integer not null check (unit_price_bdt > 0),
  line_total_bdt integer not null check (line_total_bdt >= 0)
);

create table if not exists public.fabrician_subscribers (
  email text primary key,
  language text not null default 'en' check(language in ('en','bn')),
  created_at timestamptz not null default now()
);

create table if not exists public.fabrician_reviews (
  id uuid primary key default gen_random_uuid(),
  product_id text not null references public.fabrician_products(id),
  order_id uuid references public.fabrician_orders(id),
  author text not null,
  rating integer not null check(rating between 1 and 5),
  title text not null default '',
  content text not null,
  status text not null default 'pending' check(status in ('pending','approved','hidden')),
  verified_purchase boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.fabrician_products enable row level security;
alter table public.fabrician_variants enable row level security;
alter table public.fabrician_settings enable row level security;
alter table public.fabrician_orders enable row level security;
alter table public.fabrician_order_items enable row level security;
alter table public.fabrician_subscribers enable row level security;
alter table public.fabrician_reviews enable row level security;

