-- Apply ONLY to the dedicated Fabrician/StarkiT Supabase project after review.

-- 1. Collections table
create table if not exists public.fabrician_collections (
  id text primary key,
  brand text not null,
  slug text not null unique,
  name_en text not null,
  name_bn text not null default '',
  tagline text not null default '',
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Extend fabrician_products with StarkiT 44-variant design & release gate metadata
alter table public.fabrician_products
  add column if not exists design_id text,
  add column if not exists slug text,
  add column if not exists editorial text not null default '',
  add column if not exists collection_id text references public.fabrician_collections(id),
  add column if not exists publication_status text not null default 'HOLD / NOT FOR PUBLIC SALES',
  add column if not exists sample_verified boolean not null default false,
  add column if not exists spec_verified boolean not null default false,
  add column if not exists size_chart_approved boolean not null default false,
  add column if not exists commercial_terms_approved boolean not null default false,
  add column if not exists is_licensing_required boolean not null default false,
  add column if not exists artwork_rights_note text not null default '';

create index if not exists fabrician_products_design_id_idx on public.fabrician_products(design_id);

-- 3. Extend fabrician_variants with 44-slot colorway status & release gates
alter table public.fabrician_variants
  add column if not exists slot_id text,
  add column if not exists legacy_sku text,
  add column if not exists color_code text,
  add column if not exists color_hex text,
  add column if not exists is_documented boolean not null default false,
  add column if not exists is_provisional boolean not null default true,
  add column if not exists asset_status text not null default 'NEW_MOCKUPS_REQUIRED',
  add column if not exists image_integrity text not null default 'PROVISIONAL_NO_ASSETS',
  add column if not exists asset_verified boolean not null default false,
  add column if not exists sample_verified boolean not null default false,
  add column if not exists rights_verified boolean not null default false;

create index if not exists fabrician_variants_legacy_sku_idx on public.fabrician_variants(legacy_sku);

-- 4. Product gallery/manifest table (67 planned media assets + local converted composites)
create table if not exists public.fabrician_product_images (
  id bigint generated by default as identity primary key,
  product_id text not null references public.fabrician_products(id) on delete cascade,
  variant_sku text not null references public.fabrician_variants(sku) on delete cascade,
  color text not null,
  view_type text not null,
  site_asset_path text not null,
  zip_relative_path text not null default '',
  exists_locally boolean not null default false,
  is_verified boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (variant_sku, view_type, site_asset_path)
);
create index if not exists fabrician_product_images_product_idx on public.fabrician_product_images(product_id);

