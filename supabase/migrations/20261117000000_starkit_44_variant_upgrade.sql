drop policy if exists fabrician_variants_visible on public.fabrician_variants;
create policy fabrician_variants_visible on public.fabrician_variants for select to anon, authenticated
using (
  enabled = true
  and coalesce(is_provisional, false) = false
  and exists (
    select 1 from public.fabrician_products p
    where p.id = product_id
      and p.status = 'active'
      and p.rights_cleared = true
      and coalesce(p.publication_status, 'HOLD / NOT FOR PUBLIC SALES') <> 'HOLD / NOT FOR PUBLIC SALES'
  )
);

drop policy if exists fabrician_product_images_visible on public.fabrician_product_images;
create policy fabrician_product_images_visible on public.fabrician_product_images for select to anon, authenticated
using (
  exists (
    select 1 from public.fabrician_products p
    where p.id = product_id and p.status = 'active' and p.rights_cleared = true
  )
);

