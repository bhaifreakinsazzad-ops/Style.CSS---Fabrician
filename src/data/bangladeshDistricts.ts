export const POPULAR_DISTRICT_IDS = [
  'dhaka',
  'chattogram',
  'sylhet',
  'gazipur',
  'rajshahi',
  'khulna',
] as const;

export function findDistrictById(districtId?: string): BangladeshDistrict {
  if (!districtId) return BANGLADESH_DISTRICTS[0];
  return (
    BANGLADESH_DISTRICTS.find((d) => d.id === districtId) ||
    BANGLADESH_DISTRICTS[0]
  );
}

export interface ShippingEstimate {
  district: BangladeshDistrict;
  baseFeeBDT: number;
  feeBDT: number;
  isFreeShipping: boolean;
  amountToFreeShipping: number;
  zoneLabelEn: string;
  zoneLabelBn: string;
}

export function calculateDistrictShipping(
  districtId: string,
  discountedSubtotal: number,
  itemsCount: number,
  settings: StoreSettings
): ShippingEstimate {
  const district = findDistrictById(districtId);
  const dhakaFee = Math.max(0, settings.dhakaShippingFeeBDT);
  const outsideFee = Math.max(dhakaFee, settings.outsideDhakaShippingFeeBDT);
  const suburbFee = Math.min(outsideFee, Math.round((dhakaFee + outsideFee) / 2));

  let baseFeeBDT = outsideFee;
  let zoneLabelEn = 'Nationwide Courier';
  let zoneLabelBn = 'সারা দেশ কুরিয়ার';

  if (district.zone === 'dhaka_metro') {
    baseFeeBDT = dhakaFee;
    zoneLabelEn = 'Dhaka Metro Express';
    zoneLabelBn = 'ঢাকা মেট্রো এক্সপ্রেস';
  } else if (district.zone === 'dhaka_suburb') {
    baseFeeBDT = suburbFee;
    zoneLabelEn = 'Greater Dhaka Sub-Zone';
    zoneLabelBn = 'ঢাকা উপশহর জোন';
  } else if (district.zone === 'regional_hub') {
    baseFeeBDT = outsideFee;
    zoneLabelEn = 'Divisional Priority Hub';
    zoneLabelBn = 'বিভাগীয় প্রায়োরিটি হাব';
  }

  const threshold = Math.max(0, settings.freeShippingThresholdBDT);
  const isFreeShipping = itemsCount > 0 && discountedSubtotal >= threshold;
  const feeBDT = itemsCount === 0 || isFreeShipping ? 0 : baseFeeBDT;
  const amountToFreeShipping = Math.max(0, threshold - discountedSubtotal);

  return {
    district,
    baseFeeBDT,
    feeBDT,
    isFreeShipping,
    amountToFreeShipping,
    zoneLabelEn,
    zoneLabelBn,
  };
}
